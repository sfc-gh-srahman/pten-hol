-- PTEN hands-on lab: account setup
-- Run by the first code cells of the Lab A notebook, as ACCOUNTADMIN. Safe to re-run.
-- Creates everything the two labs use. Teardown: 99_teardown.sql

USE ROLE ACCOUNTADMIN;

-- Lab role. Attendees can use their own role; grant HOL_PTEN_ROLE to them.
CREATE ROLE IF NOT EXISTS HOL_PTEN_ROLE;
GRANT ROLE HOL_PTEN_ROLE TO ROLE SYSADMIN;
SET my_user = CURRENT_USER();
GRANT ROLE HOL_PTEN_ROLE TO USER IDENTIFIER($my_user);
GRANT DATABASE ROLE SNOWFLAKE.CORTEX_USER TO ROLE HOL_PTEN_ROLE;
-- TruLens evaluation runs (Lab B) execute as tasks.
GRANT EXECUTE TASK ON ACCOUNT TO ROLE HOL_PTEN_ROLE;
GRANT CREATE DATABASE ON ACCOUNT TO ROLE HOL_PTEN_ROLE;

-- Compute
-- Adaptive warehouse: Snowflake sizes each query. Limits sized for this lab's workload
-- (largest SQL ~1.8 GB scanned, done in seconds at MEDIUM; Python training is single-node):
--   LARGE caps per-query performance with headroom; multiplier 4 covers ~20 attendees at once.
CREATE ADAPTIVE WAREHOUSE IF NOT EXISTS HOL_PTEN_WH
  WITH MAX_QUERY_PERFORMANCE_LEVEL = LARGE
       QUERY_THROUGHPUT_MULTIPLIER = 4
       COMMENT = 'PTEN HoL adaptive warehouse'
  STATEMENT_TIMEOUT_IN_SECONDS = 1800;
GRANT USAGE, OPERATE ON WAREHOUSE HOL_PTEN_WH TO ROLE HOL_PTEN_ROLE;

CREATE COMPUTE POOL IF NOT EXISTS HOL_PTEN_POOL
  MIN_NODES = 1 MAX_NODES = 2 INSTANCE_FAMILY = CPU_X64_S AUTO_SUSPEND_SECS = 600 AUTO_RESUME = TRUE;
GRANT USAGE, MONITOR ON COMPUTE POOL HOL_PTEN_POOL TO ROLE HOL_PTEN_ROLE;
GRANT BIND SERVICE ENDPOINT ON ACCOUNT TO ROLE HOL_PTEN_ROLE;

-- Allow cross-region inference if the needed model is not hosted in-region
ALTER ACCOUNT SET CORTEX_ENABLED_CROSS_REGION = 'ANY_REGION';

-- Database and schemas (created by the admin, granted to the lab role at the end)
USE WAREHOUSE HOL_PTEN_WH;
CREATE DATABASE IF NOT EXISTS HOL_PTEN_ML;
CREATE SCHEMA IF NOT EXISTS HOL_PTEN_ML.RAW;          -- tall/skinny 1-minute tag values (QuestDB-style output)
CREATE SCHEMA IF NOT EXISTS HOL_PTEN_ML.AGG;          -- per stand / state / tag aggregates, well header
CREATE SCHEMA IF NOT EXISTS HOL_PTEN_ML.LABELS;       -- NPT events (ground truth)
CREATE SCHEMA IF NOT EXISTS HOL_PTEN_ML.ML;           -- features, feature store, model registry
CREATE SCHEMA IF NOT EXISTS HOL_PTEN_ML.PREDICTIONS;  -- model scores
CREATE SCHEMA IF NOT EXISTS HOL_PTEN_ML.AGENT;        -- semantic view, tools, agent
CREATE SCHEMA IF NOT EXISTS HOL_PTEN_ML.DOCS;         -- RAG documents, chunks, Cortex Search
CREATE SCHEMA IF NOT EXISTS HOL_PTEN_ML.APP;          -- SPCS image repo + service

CREATE STAGE IF NOT EXISTS HOL_PTEN_ML.DOCS.RAW_DOCS
  DIRECTORY = (ENABLE = TRUE) ENCRYPTION = (TYPE = 'SNOWFLAKE_SSE');
CREATE STAGE IF NOT EXISTS HOL_PTEN_ML.APP.SPECS;
CREATE IMAGE REPOSITORY IF NOT EXISTS HOL_PTEN_ML.APP.IMAGES;
SHOW IMAGE REPOSITORIES IN SCHEMA HOL_PTEN_ML.APP;  -- copy repository_url for docker push

-- Notebooks on container runtime need PyPI for langchain-snowflake / trulens (Lab B)
CREATE OR REPLACE NETWORK RULE HOL_PTEN_ML.APP.HOL_PTEN_PYPI_RULE
  MODE = EGRESS TYPE = HOST_PORT
  VALUE_LIST = ('pypi.org', 'pypi.python.org', 'pythonhosted.org', 'files.pythonhosted.org');
CREATE OR REPLACE EXTERNAL ACCESS INTEGRATION HOL_PTEN_PYPI_EAI
  ALLOWED_NETWORK_RULES = (HOL_PTEN_ML.APP.HOL_PTEN_PYPI_RULE) ENABLED = TRUE;
GRANT USAGE ON INTEGRATION HOL_PTEN_PYPI_EAI TO ROLE HOL_PTEN_ROLE;


-- Hand the lab objects to the lab role
GRANT OWNERSHIP ON DATABASE HOL_PTEN_ML TO ROLE HOL_PTEN_ROLE COPY CURRENT GRANTS;
GRANT ALL ON ALL SCHEMAS IN DATABASE HOL_PTEN_ML TO ROLE HOL_PTEN_ROLE;
GRANT ALL ON FUTURE SCHEMAS IN DATABASE HOL_PTEN_ML TO ROLE HOL_PTEN_ROLE;
GRANT ALL ON FUTURE TABLES IN DATABASE HOL_PTEN_ML TO ROLE HOL_PTEN_ROLE;
GRANT READ, WRITE ON STAGE HOL_PTEN_ML.DOCS.RAW_DOCS TO ROLE HOL_PTEN_ROLE;
GRANT READ, WRITE ON IMAGE REPOSITORY HOL_PTEN_ML.APP.IMAGES TO ROLE HOL_PTEN_ROLE;
